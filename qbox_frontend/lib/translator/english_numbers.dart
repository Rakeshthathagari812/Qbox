final Map<String, String> _byWord = {
  for (final e in _words.entries)
    for (final w in e.value) _shape(w): e.key,
};

/// Long and short endings, and the joiners inside words, are the same.
String _shape(String w) => w
    .replaceAll(RegExp('[‌‍़]'), '')
    .replaceAll('ీ', 'ి')
    .replaceAll('ी', 'ि')
    .replaceAll('ೀ', 'ಿ')
    .replaceAll('ீ', 'ி');

String englishNumberWords(String text) => text.replaceAllMapped(RegExp(r'[^\s,.!?।]+'), (m) => _byWord[_shape(m[0]!)] ?? m[0]!);
